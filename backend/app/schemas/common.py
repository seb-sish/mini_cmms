from typing import Any, Optional
from pydantic import BaseModel, Field

class InvalidParam(BaseModel):
    name: str = Field(description="Name of the invalid parameter or field")
    reason: str = Field(description="Reason why the parameter is invalid")

class ProblemDetail(BaseModel):
    type: str = Field(
        default="about:blank",
        description="A URI reference that identifies the problem type"
    )
    title: str = Field(description="A short, human-readable summary of the problem type")
    status: int = Field(description="The HTTP status code generated by the origin server")
    detail: str = Field(description="A human-readable explanation specific to this occurrence of the problem")
    instance: Optional[str] = Field(
        default=None,
        description="A URI reference that identifies the specific occurrence of the problem"
    )
    code: str = Field(description="Stable machine-readable error code")
    invalid_params: Optional[list[InvalidParam]] = Field(
        default=None,
        description="Validation errors by field"
    )

class PaginatedResponse(BaseModel):
    items: list[Any]
    total: int
    limit: int
    offset: int
